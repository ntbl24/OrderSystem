create table product (
    id varchar(36) primary key,
    created_at timestamp,
    updated_at timestamp,
    deleted boolean,
    title varchar(255),
    category varchar(255),
    description varchar(2000),
    price numeric(19,0),
    stock integer,
    sku varchar(255),
    seller_id varchar(255),
    reserved integer,
    version bigint, constraint product_inventory check(stock >= 0 and reserved >= 0 and reserved <= stock), constraint product_price check(price > 0), constraint product_seller check(seller_id is not null and length(seller_id)>0), unique(sku)
);
create table cart (
    id varchar(36) primary key,
    created_at timestamp,
    updated_at timestamp,
    deleted boolean,
    user_id varchar(255),
    version bigint,
    sub_total numeric(19,0),
    shipping_cost numeric(19,0),
    total numeric(19,0),
    tax numeric(19,0),
    coupon_code varchar(255),
    discount numeric(19,0), unique(user_id), constraint cart_owner check(user_id is not null)
);
create table cart_item (
    cart_id varchar(36) not null references cart(id),
    line_index integer not null,
    product_id varchar(255) not null,
    product_name varchar(255) not null,
    quantity integer not null,
    unit_price numeric(19,0) not null,
    sub_total numeric(19,0) not null, primary key(cart_id,line_index), check(quantity>0), check(unit_price>0));
    create table purchase_order (
    id varchar(36) primary key,
    created_at timestamp,
    updated_at timestamp,
    deleted boolean,
    user_id varchar(255),
    order_number varchar(255),
    subtotal numeric(19,0),
    shipping_cost numeric(19,0),
    shipping_address varchar(2000),
    payment_method varchar(255),
    payment_status varchar(255),
    order_status varchar(255),
    order_date timestamp,
    estimated_delivery_date timestamp,
    notes varchar(2000),
    seller_id varchar(255),
    expires_at timestamptz,
    payment_id varchar(255),
    review_payment_id varchar(255),
    reservation_status varchar(255),
    version bigint, unique(order_number), constraint order_amount check(subtotal > 0 and shipping_cost >= 0), constraint order_state check(order_status in ('UNPAID','PAID','CANCELLED','EXPIRED','REFUNDED','PAYMENT_REVIEW')), constraint reservation_state check(reservation_status in ('HELD','CONSUMED','RELEASED','RETURNED')), constraint order_owner check(user_id is not null and seller_id is not null and expires_at is not null)
);
create table order_item (
    order_id varchar(36) not null references purchase_order(id),
    line_index integer not null,
    product_id varchar(255) not null,
    product_name varchar(255) not null,
    sku varchar(255) not null,
    quantity integer not null,
    unit_price numeric(19,0) not null,
    subtotal numeric(19,0) not null, primary key(order_id,line_index), check(quantity>0), check(unit_price>0));
    create table shipping (
    id varchar(36) primary key,
    created_at timestamp,
    updated_at timestamp,
    deleted boolean,
    version bigint,
    order_id varchar(255),
    user_id varchar(255),
    tracking_number varchar(255),
    carrier varchar(255),
    service_type varchar(255),
    weight numeric(19,2),
    weight_unit varchar(255),
    shipping_cost numeric(19,2),
    status varchar(255),
    estimated_delivery_date timestamp,
    actual_delivery_date timestamp,
    origin_address varchar(255),
    origin_city varchar(255),
    origin_state varchar(255),
    origin_country varchar(255),
    origin_postal_code varchar(255),
    destination_address varchar(255),
    destination_city varchar(255),
    destination_state varchar(255),
    destination_country varchar(255),
    destination_postal_code varchar(255),
    notes varchar(2000),
    label_url varchar(255),
    return_label_url varchar(255),
    signature_required boolean,
    insurance_required boolean,
    declared_value numeric(19,2),
    customs_info varchar(255),
    customs_value varchar(255),
    customs_currency varchar(255)
);
create index order_buyer_idx on purchase_order(user_id,created_at desc);
create index order_expiry_idx on purchase_order(order_status,expires_at,id);
create index shipment_order_idx on shipping(order_id);

